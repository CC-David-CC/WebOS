import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import puppeteer from 'puppeteer-core';

const base=process.env.CODI_GARDEN_URL||'http://127.0.0.1:18360/';
const browser=await puppeteer.connect({browserURL:process.env.CODI_TEST_CDP||'http://127.0.0.1:19262',protocolTimeout:120000});
const context=await browser.createBrowserContext(),page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));page.on('dialog',dialog=>dialog.accept());
const click=label=>page.evaluate(label=>{const button=[...document.querySelectorAll('.garden-view button')].find(node=>node.textContent===label);if(!button)throw Error('Missing button: '+label);button.click()},label);
try{
 const phone=process.env.CODI_PHONE==='1';
 await page.setViewport(phone?{width:412,height:915,isMobile:true,hasTouch:true}:{width:1366,height:900});
 const manifest=JSON.parse(await readFile(process.env.CODI_GARDEN_MANIFEST||'.build/garden-defense-test/apps.json','utf8'));
 const entry='/'+manifest.apps[0].path.replace(/^assets\/desktop\//,'');
 await page.goto(base+'?app='+encodeURIComponent(entry));
 await page.waitForFunction(()=>window.instances?.length===2);
 await page.waitForFunction(()=>document.querySelectorAll('.garden-stage-wrap canvas').length===2,{timeout:30000});
 assert.equal(await page.$$('.garden-view').then(nodes=>nodes.length),2);
 assert.match(await page.$$eval('.garden-advisor',nodes=>nodes[0].textContent),/Rive artwork.*pending/);
 await page.select('.garden-view [aria-label="Garden map"]','1');
 await click('Next site ▶');
 await click('Build rapid');
 assert.match(await page.$eval('.garden-summary',node=>node.textContent),/1\/8 towers/);
 await click('Upgrade tower');
 await click('Start wave');
 await page.waitForFunction(()=>document.querySelector('.garden-summary')?.textContent.includes('active'));
 await page.waitForFunction(()=>document.querySelector('.garden-summary')?.textContent.match(/Wave 1\/10/),{timeout:10000});
 await page.evaluate(()=>window.instances[0].win.classList.remove('focused'));
 await page.waitForFunction(()=>document.querySelector('.garden-status')?.textContent.includes('window lost attention'));
 await page.evaluate(()=>{window.instances[0].win.classList.add('focused')});
 await click('Resume');
 await page.waitForFunction(()=>document.querySelector('.garden-status')?.textContent.includes('Garden running'));
 await page.waitForFunction(()=>!document.querySelector('.garden-warning')?.textContent);
 await page.evaluate(()=>document.querySelector('.garden-save').open=true);
 await page.$eval('[aria-label="Garden save path"]',input=>input.value='/Garden Defense.game.json');
 await click('Save to My files');
 await page.waitForFunction(()=>document.querySelector('.garden-status')?.textContent.includes('syncing with the server'));
 const saved=JSON.parse(await page.evaluate(()=>new TextDecoder().decode(window.fileStore.get('/Garden Defense.game.json').data)));
 assert.equal(saved.appId,'garden-defense');assert.equal(saved.payload.mapId,1);
 await page.evaluate(()=>window.fileStore.set('/bad.game.json',{data:new TextEncoder().encode('{bad'),version:'bad',status:'synced'}));
 await page.evaluate(()=>window.targetPath='/bad.game.json');
 await click('Open from My files');
 await page.waitForFunction(()=>document.querySelector('.garden-status')?.textContent.includes('Could not open'));
 await page.evaluate(()=>window.instances[0].app.dispose());
 await page.evaluate(()=>window.instances[0].app.dispose());
 await page.evaluate(()=>window.instances[0].app.element.remove());
 assert.equal(await page.$$('.garden-view').then(nodes=>nodes.length),1);
 assert.deepEqual(errors,[]);
 console.log(`PASS ${phone?'phone':'desktop'} two Garden Defense instances, build/upgrade, wave, save, invalid recovery and disposal`);
}finally{await context.close();await browser.disconnect()}
